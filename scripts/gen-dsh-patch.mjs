#!/usr/bin/env node
/**
 * Write examples/dsh-web.patch.yml with ABSOLUTE paths.
 * Official first-plugin tutorial requires absolute `name:` paths for
 * `dsh web --patch <file>`.
 */
import { writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(dirname(fileURLToPath(import.meta.url)))
const skillsDir = join(root, 'skills')

const yaml = `# Generated by scripts/gen-dsh-patch.mjs — do not hand-edit paths.
# Load into official DeepSeek Harness:
#
#   npx @deepseek-ai/dsh web --patch ${join(root, 'examples/dsh-web.patch.yml')}
#
# Then open http://127.0.0.1:3080 → Settings → Plugins.
# You should see image-core / image-compose / image-guard / image-assets /
# image-skills / image-provider-mock / image-tools / image-ui (ACTIVE).
# Chat tools should include image_skill_plan, image_generate, image_edit,
# image_describe, image_compose, image_assets.

- insert:
    - id: image-core
      name: '${join(root, 'packages/core/src/index.ts')}'

    - id: image-compose
      name: '${join(root, 'packages/compose/src/index.ts')}'

    - id: image-guard
      name: '${join(root, 'packages/guard/src/index.ts')}'

    - id: image-assets
      name: '${join(root, 'packages/assets/src/index.ts')}'
      config:
        workspaceRoot: !!js process.cwd()
        keepLastTasks: 50

    - id: image-skills
      name: '${join(root, 'packages/skills/src/index.ts')}'
      config:
        dir: '${skillsDir}'
        enabled:
          - cinema-dna-21x9x3
          - life-force-portrait
          - photography-simulation
          - movie-poster
          - character-casting

    - id: image-provider-mock
      name: '${join(root, 'packages/provider-mock/src/index.ts')}'

    - id: image-tools
      name: '${join(root, 'packages/tools/src/index.ts')}'
      config:
        limits:
          concurrency: 3
          perTaskTimeoutMs: 180000
          maxImagesPerCall: 4

    - id: image-ui
      name: '${join(root, 'packages/ui/src/index.ts')}'
`

const out = join(root, 'examples/dsh-web.patch.yml')
writeFileSync(out, yaml)
console.log('wrote', out)
